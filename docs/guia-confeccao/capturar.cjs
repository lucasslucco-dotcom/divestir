// Tira as telas do painel (site local, dados de mentira) para o guia da confecção.
const { chromium } = require('playwright');
const fs = require('fs');
const SITE = 'http://localhost:3100';
const fora = __dirname + '/telas';
const caixas = {};
(async () => {
  const navegador = await chromium.launch();
  const ctx = await navegador.newContext({ viewport: { width: 1280, height: 860 }, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  const caixa = async (nome, loc) => { const b = await loc.first().boundingBox().catch(() => null); caixas[nome] = b; if (!b) console.log('sem caixa:', nome); };
  const tela = async (nome) => { await p.waitForTimeout(500); await p.screenshot({ path: `${fora}/${nome}.png` }); };
  await p.goto(`${SITE}/painel/entrar`); await p.waitForSelector('#email');
  await p.fill('#email', 'contato@suaconfeccao.com.br');
  await caixa('entrar-email', p.locator('#email')); await caixa('entrar-senha', p.locator('#senha')); await caixa('entrar-botao', p.locator('button[type=submit]'));
  await tela('1-entrar');
  await p.fill('#email', 'confeccao@teste.com'); await p.fill('#senha', process.env.SENHA_DE_TESTE);
  await p.click('button[type=submit]'); await p.waitForURL(`${SITE}/painel`); await p.waitForTimeout(1500);
  await caixa('quadro-producao', p.locator('h2:has-text("Em produção"), h3:has-text("Em produção")'));
  await caixa('quadro-cartao', p.locator('a:has-text("João Pedro")'));
  await caixa('topo-nome', p.locator('a[href="/painel/senha"]'));
  await tela('2-quadro');
  console.log('colunas:', (await p.locator('h2, h3').allInnerTexts()).join(' | '));
  await p.locator('a:has-text("João Pedro")').first().click(); await p.waitForURL(/pedidos\/\d+/); await p.waitForSelector('h4:has-text("Arquivos para a confecção")', { timeout: 60000 }); await p.waitForTimeout(2500);
  await caixa('pedido-botao', p.locator('button:has-text("Informar o rastreio")'));
  await tela('3-pedido-topo');
  const bloco = p.locator('div', { has: p.locator('h4:has-text("Arquivos para a confecção")') }).last();
  await bloco.evaluate((e) => window.scrollTo(0, e.getBoundingClientRect().top + scrollY - 430)); await p.waitForTimeout(600);
  await caixa('arq-bloco', bloco);
  for (const [k, t] of [['arq-estampa', 'Baixar a estampa pronta'], ['arq-peito', 'Baixar a marca do peito'], ['arq-recorte', 'Baixar só o recorte']]) await caixa(k, bloco.locator(`button:has-text("${t}")`));
  await tela('4-arquivos');
  console.log('texto do bloco:', (await bloco.innerText()).replace(/\n+/g, ' | ').slice(0, 600));
  const entrega = p.locator('h2:has-text("Cliente e entrega"), h3:has-text("Cliente e entrega")').first();
  await entrega.evaluate((e) => window.scrollTo(0, e.getBoundingClientRect().top + scrollY - 120)); await p.waitForTimeout(600);
  await caixa('entrega-titulo', entrega);
  await caixa('entrega-endereco', p.locator('text=Entregar em'));
  await tela('5-entrega');
  await p.evaluate(() => window.scrollTo(0, 0)); await p.waitForTimeout(300);
  await p.locator('button:has-text("Informar o rastreio")').first().click(); await p.waitForTimeout(700);
  const campo = p.locator('dialog input, [role=dialog] input').first();
  await campo.fill('BR123456789BR').catch((e) => console.log('sem campo no diálogo', e.message.slice(0, 80)));
  await caixa('rastreio-campo', campo); await caixa('rastreio-confirmar', p.locator('dialog button[type=submit], [role=dialog] button[type=submit]'));
  console.log('botões do diálogo:', (await p.locator('dialog button, [role=dialog] button').allInnerTexts()).join(' | '));
  await tela('6-rastreio');
  await p.keyboard.press('Escape');
  await p.goto(`${SITE}/painel/senha`); await p.waitForTimeout(1200);
  await caixa('senha-botao', p.locator('button[type=submit]'));
  await tela('7-senha');
  fs.writeFileSync(`${fora}/caixas.json`, JSON.stringify(caixas, null, 1));
  await navegador.close();
})().catch((e) => { console.log('FALHOU', e.message.slice(0, 600)); process.exit(1); });
